export function packTracks(id) {
  const pack = PACKS.find(p => p.id === id);
  return pack ? pack.idx.map(i => {
    const [title, artist, genre, duration, bpm, key, cues] = PACK_ROWS[i];
    return { id: 'rb-' + (i + 1), title, artist, genre, duration, bpm, key, cues: (cues || []).map(([time, label]) => ({ time, label })) };
  }) : [];
}
